#define FONT_FIRST_CHAR  ' '
#define FONT_LAST_CHAR    '~'
#define FONT_COUNT       (FONT_LAST_CHAR - FONT_FIRST_CHAR + 1)

/* ---- Renderer implementation ------------------------------------------- */

void renderer_init(renderer_t *r, uint16_t *fb, int fb_fd) {
    r->fb = fb;
    r->fb_fd = fb_fd;
    r->pan_yoffset = 0;
    r->needs_redraw = 1;
}

void render_clear(renderer_t *r) {
    if (!r->fb) return;
    /* Clear the active buffer only (not both — saves time) */
    memset(r->fb, 0, RENDER_BUF_SIZE);
    r->needs_redraw = 1;
}

void render_fill_rect(renderer_t *r, int x, int y, int w, int h,
                      uint16_t color) {
    if (!r->fb) return;
    int xend = x + w, yend = y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (xend > RENDER_FB_W) xend = RENDER_FB_W;
    if (yend > RENDER_FB_H) yend = RENDER_FB_H;
    int stride_pixels = RENDER_STRIDE / 2;
    for (int py = y; py < yend; py++) {
        uint16_t *row = r->fb + py * stride_pixels;
        for (int px = x; px < xend; px++)
            row[px] = color;
    }
    r->needs_redraw = 1;
}

void render_draw_rect(renderer_t *r, int x, int y, int w, int h,
                      uint16_t color) {
    if (w < 1 || h < 1) return;
    render_fill_rect(r, x, y, w, 1, color);         /* top */
    render_fill_rect(r, x, y + h - 1, w, 1, color);  /* bottom */
    render_fill_rect(r, x, y, 1, h, color);          /* left */
    render_fill_rect(r, x + w - 1, y, 1, h, color);  /* right */
}

void render_draw_hline(renderer_t *r, int x, int y, int w, uint16_t color) {
    render_fill_rect(r, x, y, w, 1, color);
}

void render_fill_circle(renderer_t *r, int cx, int cy, int rad, uint16_t color) {
    if (!r->fb || rad < 1) return;
    int stride_pixels = RENDER_STRIDE / 2;
    int r2 = rad * rad;
    for (int dy = -rad; dy <= rad; dy++) {
        int py = cy + dy;
        if (py < 0 || py >= RENDER_FB_H) continue;
        int rem = r2 - dy * dy;
        if (rem < 0) continue;
        int span = 0;
        while (span * span <= rem) span++;
        span--;  /* largest dx with dx*dx <= rem */
        int x0 = cx - span, x1 = cx + span;
        if (x0 < 0) x0 = 0;
        if (x1 >= RENDER_FB_W) x1 = RENDER_FB_W - 1;
        uint16_t *row = r->fb + py * stride_pixels;
        for (int px = x0; px <= x1; px++) row[px] = color;
    }
    r->needs_redraw = 1;
}

void render_blit_rgb565(renderer_t *r, int dx, int dy, int dw, int dh,
                        const uint16_t *src, int sw, int sh) {
    if (!r->fb || !src || sw <= 0 || sh <= 0 || dw <= 0 || dh <= 0) return;
    int stride_pixels = RENDER_STRIDE / 2;
    /* Clip destination rectangle to the screen; track how much of the source
     * each axis contributes so we still sample src correctly after clipping. */
    int sxd = 0, syd = 0;
    int dxe = dx + dw, dye = dy + dh;
    if (dx < 0) { sxd = -dx; dx = 0; }
    if (dy < 0) { syd = -dy; dy = 0; }
    if (dxe > RENDER_FB_W) dxe = RENDER_FB_W;
    if (dye > RENDER_FB_H) dye = RENDER_FB_H;
    if (dx >= dxe || dy >= dye) return;

    for (int py = dy; py < dye; py++) {
        int dyy = py - dy + syd;          /* dest-relative y incl. clip offset */
        int sy = dyy * sh / dh;           /* nearest-neighbor src y */
        if (sy >= sh) sy = sh - 1;
        const uint16_t *srow = src + (size_t)sy * sw;
        uint16_t *drow = r->fb + (size_t)py * stride_pixels;
        for (int px = dx; px < dxe; px++) {
            int dxx = px - dx + sxd;      /* dest-relative x incl. clip offset */
            int sx = dxx * sw / dw;       /* nearest-neighbor src x */
            if (sx >= sw) sx = sw - 1;
            drow[px] = srow[sx];
        }
    }
    r->needs_redraw = 1;
}

void render_char(renderer_t *r, int x, int y, char c, int scale,
                 uint16_t color) {
    if (!r->fb) return;
    if (font_available()) {
        font_draw_char(r->fb, x, y, c, font_px_for_scale(scale), color);
        r->needs_redraw = 1;
        return;
    }
    /* ---- 8x12 bitmap fallback ---- */
    if (c < FONT_FIRST_CHAR || c > FONT_LAST_CHAR) c = '?';
    int idx = c - FONT_FIRST_CHAR;
    const uint8_t *glyph = FONT8x12[idx];

    int stride_pixels = RENDER_STRIDE / 2;
    for (int gy = 0; gy < FONT_H; gy++) {
        uint8_t row_bits = glyph[gy];
        for (int gx = 0; gx < FONT_W; gx++) {
            if (row_bits & (0x80 >> gx)) {
                int px = x + gx * scale;
                int py = y + gy * scale;
                /* Draw a scale×scale block */
                for (int sy = 0; sy < scale; sy++) {
                    if (py + sy >= RENDER_FB_H) break;
                    uint16_t *line = r->fb + (py + sy) * stride_pixels;
                    for (int sx = 0; sx < scale; sx++) {
                        if (px + sx >= RENDER_FB_W) break;
                        line[px + sx] = color;
                    }
                }
            }
        }
    }
    r->needs_redraw = 1;
}

int render_text(renderer_t *r, int x, int y, const char *s, int scale,
                uint16_t color) {
    if (!s) return x;
    if (font_available()) {
        int nx = font_draw_text(r->fb, x, y, s, font_px_for_scale(scale), color);
        r->needs_redraw = 1;
        return nx;
    }
    /* ---- 8x12 bitmap fallback ---- */
    int cx = x;
    int char_w = FONT_W * scale + scale;  /* +1px spacing per scale */
    for (; *s; s++) {
        if (*s == '\n') { cx = x; y += FONT_H * scale + scale; continue; }
        render_char(r, cx, y, *s, scale, color);
        cx += char_w;
    }
    return cx;
}

void render_text_centered(renderer_t *r, int x, int y, int w,
                           const char *s, int scale, uint16_t color) {
    if (!s) return;
    int text_w = render_text_width(s, scale);
    int start_x = x + (w - text_w) / 2;
    if (start_x < x) start_x = x;
    render_text(r, start_x, y, s, scale, color);
}

void render_text_right(renderer_t *r, int x_right, int y,
                       const char *s, int scale, uint16_t color) {
    if (!s) return;
    int text_w = render_text_width(s, scale);
    render_text(r, x_right - text_w, y, s, scale, color);
}

int render_text_line_height(int scale) {
    if (font_available())
        return font_line_height(font_px_for_scale(scale)) + 2;
    return FONT_H * scale + scale;
}

int render_text_wrap(renderer_t *r, int x, int y, int w, int max_lines,
                     const char *s, int scale, uint16_t color) {
    if (!s) return y;
    int line_h = render_text_line_height(scale);
    int cy = y;
    int line = 0;
    const char *p = s;
    while (*p && line < max_lines) {
        while (*p == ' ') p++;
        if (!*p) break;

        /* Measure actual glyph advances. The previous wrapper divided the
         * width by the advance of "M", which made ordinary prose wrap at
         * roughly half the available width. */
        int line_w = 0;
        const char *last_space = NULL;
        const char *q = p;
        while (*q && *q != '\n') {
            char glyph[2] = {*q, '\0'};
            int glyph_w = render_text_width(glyph, scale);
            if (q > p && line_w + glyph_w > w) break;
            if (*q == ' ') last_space = q;
            line_w += glyph_w;
            q++;
        }

        const char *next = q;
        if (*q && *q != '\n' && last_space && last_space > p)
            next = last_space;

        const char *draw_end = next;
        while (draw_end > p && draw_end[-1] == ' ') draw_end--;
        int draw_len = (int)(draw_end - p);

        /* Draw the substring */
        char buf[256];
        int cp = draw_len < (int)sizeof(buf) - 1 ? draw_len : (int)sizeof(buf) - 1;
        memcpy(buf, p, cp);
        buf[cp] = '\0';
        render_text(r, x, cy, buf, scale, color);

        cy += line_h;
        line++;
        p = next;
        while (*p == ' ') p++;
        if (*p == '\n') p++;
    }
    return cy;
}

void render_time(renderer_t *r, int x, int y, int64_t ms, int scale,
                 uint16_t color) {
    int total_sec = (int)(ms / 1000);
    int h = total_sec / 3600;
    int m = (total_sec % 3600) / 60;
    int s = total_sec % 60;
    char buf[16];
    if (h > 0)
        snprintf(buf, sizeof(buf), "%d:%02d:%02d", h, m, s);
    else
        snprintf(buf, sizeof(buf), "%d:%02d", m, s);
    render_text(r, x, y, buf, scale, color);
}

void render_progress_bar(renderer_t *r, int x, int y, int w, int h,
                         double fraction, uint16_t fill_color,
                         uint16_t bg_color) {
    render_fill_rect(r, x, y, w, h, bg_color);
    if (fraction < 0) fraction = 0;
    if (fraction > 1) fraction = 1;
    int fill_w = (int)(w * fraction);
    if (fill_w > 0)
        render_fill_rect(r, x, y, fill_w, h, fill_color);
}

void render_flip(renderer_t *r) {
    if (r->fb_fd >= 0) {
        struct fb_var_screeninfo vinfo;
        if (ioctl(r->fb_fd, FBIOGET_VSCREENINFO, &vinfo) >= 0) {
            vinfo.yoffset = r->pan_yoffset;
            ioctl(r->fb_fd, FBIOPAN_DISPLAY, &vinfo);
        }
    }
    r->needs_redraw = 0;
}

int render_text_width(const char *s, int scale) {
    if (!s) return 0;
    if (font_available()) return font_text_width(s, font_px_for_scale(scale));
    int char_w = FONT_W * scale + scale;
    return (int)strlen(s) * char_w;
}
